"""Stage 7: assemble the computed numbers for the Phase 2 progress report.

This generates FACTS ONLY - tables of what the pipeline measured, in markdown,
so that the team can write the progress report and viva answers from real
numbers instead of re-deriving them by hand. It deliberately does not write
the interpretation: that is the team's own work and is what C7 (technical
understanding) and C10 (individual contribution) are assessed on.

Usage: python 07_report_pack.py  ->  reports/phase2_numbers.md
"""

import glob
import json
import os
import sys

import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from config import PROCESSED_DIR, RAW_DIR, VARIANT, WINDOWS

OUT = ("reports/phase2_numbers.md" if VARIANT == "full"
       else "reports/core/phase2_numbers_core.md")


def read_csv(name):
    path = f"{PROCESSED_DIR}/{name}"
    return pd.read_csv(path) if os.path.exists(path) else None


def md_table(df):
    return df.to_markdown(index=False) if df is not None and not df.empty else "_not generated yet_"


def collection_table():
    """Per-subreddit collection stats.

    Read from the per-subreddit done-markers rather than collection_log_*.json:
    the log is only written when a whole window finishes, so a run that was
    interrupted and resumed leaves its finished subreddits out of the log.
    The markers are written as each subreddit completes.
    """
    rows = []
    for path in sorted(glob.glob(f"{RAW_DIR}/.done_*")):
        with open(path, encoding="utf-8") as f:
            rows.append(json.load(f))
    if not rows:  # fall back to the window logs
        for key in WINDOWS:
            path = f"{RAW_DIR}/collection_log_{key}.json"
            if not os.path.exists(path):
                continue
            with open(path, encoding="utf-8") as f:
                rows.extend(json.load(f))
    if not rows:
        return None
    df = pd.DataFrame(rows)
    # A subreddit may appear twice if a run was resumed; keep the last entry.
    df = df.drop_duplicates(subset=["window", "subreddit"], keep="last")
    df = df.sort_values(["window", "subreddit"])
    return df[["window", "subreddit", "posts_kept", "comments",
               "posts_hitting_comment_cap", "posts_below_comment_threshold",
               "comment_fetch_failures"]]


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)

    quality_path = f"{PROCESSED_DIR}/quality_report.json"
    quality = {}
    if os.path.exists(quality_path):
        with open(quality_path, encoding="utf-8") as f:
            quality = json.load(f)

    lines = [
        "# Phase 2 — computed numbers",
        "",
        "Generated by `scripts/07_report_pack.py` from the pipeline outputs.",
        "These are measurements, not the write-up: the interpretation, the",
        "progress-vs-plan narrative and the viva answers are the team's own.",
        "",
        "## 1. Study design",
        "",
        "| Window | Dates | Length |",
        "|---|---|---|",
    ]
    for key, w in WINDOWS.items():
        days = (pd.Timestamp(w["end"]) - pd.Timestamp(w["start"])).days
        lines.append(f"| {w['label']} | {w['start']} to {w['end']} (exclusive) | {days} days |")

    lines += ["", "## 2. What was collected", "", md_table(collection_table()), ""]

    if quality:
        lines += ["## 3. Data quality after cleaning", "",
                  "| Measure | Value |", "|---|---|"]
        for k, v in quality.items():
            if k == "by_window":
                continue
            lines.append(f"| {k.replace('_', ' ')} | {v:,} |" if isinstance(v, int)
                         else f"| {k.replace('_', ' ')} | {v} |")
        lines.append("")
        bw = quality.get("by_window", {})
        if bw:
            lines += ["### Per window", "",
                      md_table(pd.DataFrame(bw).T.reset_index()
                               .rename(columns={"index": "window"})), ""]

    for title, name in [("## 4. Exploratory analysis", "eda_summary.csv"),
                        ("## 5. Reply-network comparison", "network_metrics.csv"),
                        ("## 6. Source-sharing comparison", "source_metrics.csv")]:
        df = read_csv(name)
        lines += [title, "", md_table(df.T.reset_index() if df is not None and len(df) <= 3
                                      else df), ""]

    for key in WINDOWS:
        df = read_csv(f"community_profile_{key}.csv")
        if df is not None and not df.empty:
            top = (df.sort_values(["community", "pct_of_community"],
                                  ascending=[True, False])
                   .groupby("community").head(3))
            lines += [f"### Detected communities — {WINDOWS[key]['label']}", "",
                      md_table(top), ""]

    cross = read_csv("cross_community_summary.csv")
    if cross is not None:
        lines += [
            "### Cross-community replies, with and without the dominant pair",
            "",
            "Most cross-community replies run between two large general-audience",
            "communities. RQ2 asks about contact between different discussion",
            "communities, so the share is also given with that pair removed.",
            "",
            md_table(cross), "",
        ]

    net_rb = read_csv("robustness_networks.csv")
    src_rb = read_csv("robustness_sources.csv")
    if net_rb is not None or src_rb is not None:
        lines += [
            "## 7. Robustness checks",
            "",
            "February 2026 is the larger window on every raw count, and neither",
            "modularity nor source overlap is size-invariant, so each comparison",
            "is repeated with the larger window subsampled down to the smaller.",
            "",
        ]
        if src_rb is not None:
            mean_src = (src_rb.groupby("window")[
                ["unique_domains", "mean_pairwise_source_overlap",
                 "mean_source_concentration_gini", "domains_exclusive_to_one_sub"]]
                .mean().round(4).reset_index())
            lines += ["### Source metrics at equal share count", "",
                      md_table(mean_src), ""]
        if net_rb is not None:
            sampled = net_rb[net_rb["rep"] != "full"]
            if not sampled.empty:
                grouped = sampled.groupby("window")
                mean_net = (grouped[
                    ["nodes", "modularity", "ei_index_louvain",
                     "ei_index_by_subreddit"]]
                    .mean().round(4).reset_index())
                spread = (grouped[
                    ["modularity", "ei_index_louvain", "ei_index_by_subreddit"]]
                    .std().round(4).reset_index())
                lines += ["### Network metrics at equal edge count", "",
                          f"Mean over {sampled['rep'].nunique()} subsamples:", "",
                          md_table(mean_net), "",
                          "Standard deviation across subsamples:", "",
                          md_table(spread), ""]
            full = net_rb[net_rb["rep"] == "full"]
            if not full.empty and "modularity_above_null" in full:
                cols = ["window", "modularity_unweighted", "null_modularity",
                        "modularity_above_null"]
                lines += ["### Observed vs degree-preserving random null", "",
                          "Both sides computed without edge weights.", "",
                          md_table(full[cols].round(4)), ""]

    lines += [
        "## 8. Figures",
        "",
        "- `figures/volume_by_day.png` — activity per day, both windows overlaid",
        "- `figures/posts_by_subreddit.png` — where discussion happened",
        "- `figures/comment_length.png` — comment length distributions",
        "- `figures/top_domains.png` — most-shared external sources",
        "- `figures/networks/*.gexf` — reply and source networks, for Gephi",
        "",
    ]

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
